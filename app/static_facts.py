_compiled = [(f, [re.compile(r"(?<![a-z])" + re.escape(k.strip()) + r"(?![a-z])") for k in f["keys"]]) for f in FACTS]


def static_connect(text, limit=2):
    t = (text or "").lower()
    out = []
    for f, pats in _compiled:
        if any(p.search(t) for p in pats):
            out.append({"title": f["title"], "facts": f["facts"], "upsc": f["upsc"]})
        if len(out) >= limit:
            break
    return out
